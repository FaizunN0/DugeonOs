export function evaluateEnding(state) {
  const f = state.flags;
  const st = state.stats;

  // ===== HUB GRIND (easter egg: habiskan semua kuota hub hari 1-10) =====
  if (f.hubGrind) return resolve("hub_grind", state);

  // ===== NESTED TWIST (4) =====
  if (f.devConsole && st.devSuspicion >= 40) return resolve("simulasi_berlapis", state);
  if (f.betrayedUnion && f.hqTest && st.devSuspicion >= 30) return resolve("mogok_palsu", state);
  if (f.memeWar && f.taxDungeon) return resolve("pemerintah_bawang", state);
  if (f.devConsole && (f.leanOnion || f.secretHero)) return resolve("realitas_berlapis_2", state);

  // ===== PLOT TWIST (5) =====
  if (f.gremWasBoss) return resolve("grem_bos_sebenarnya", state);
  if (f.secretHero) return resolve("kamu_hero", state);
  if (f.joinedHQ && f.hqTest) return resolve("hq_adalah_minion", state);
  if (f.dungeonItuKamu) return resolve("dungeon_itukamu", state);
  if (f.betrayedUnion && f.hqTest && st.devSuspicion < 30) return resolve("mogok_palsu_light", state);

  // ===== ANOMALI (6) =====
  if (f.metaBreak) return resolve("bawang_menangis", state);
  if (f.dream) return resolve("simulasi_kecil", state);
  if (f.loop) return resolve("time_loop", state);
  if (f.gravity) return resolve("gravity_off", state);
  if (f.aiMinion) return resolve("minion_digital", state);
  if (f.goldSick) return resolve("gold_sick", state);
  if (f.cheated) return resolve("ketahuan_curang", state);

  // ===== UNIK (8) =====
  if (f.leanOnion) return resolve("kultus_bawang", state);
  if (st.reputation >= 80 && f.mediaSavvy) return resolve("dungeongram_viral", state);
  if (f.freedMinions) return resolve("pacifist", state);
  if (st.morale >= 55 && st.stability >= 55 && !f.exploit && !f.leanOnion && !f.treatWell) return resolve("cafe_dungeon", state);
  if (f.mediaSavvy && st.reputation >= 50) return resolve("influencer_semua", state);
  if (f.unionSide) return resolve("union_ceo", state);
  if (st.reputation >= 60 && f.treatWell) return resolve("dungeon_resort", state);
  if (st.gold >= 1000 && st.stability >= 55) return resolve("franchise", state);

  // ===== BIASA (10) =====
  if (st.stability <= 10) return resolve("kolaps", state);
  if (st.gold >= 1500) return resolve("pensiun_kaya", state);
  if (st.morale >= 60 && st.stability >= 60 && f.treatWell) return resolve("boss_model", state);
  if (st.morale <= 35 && f.exploit) return resolve("tiran", state);
  if (st.morale >= 40 && f.exploit) return resolve("quiet_quit", state);
  if (st.unionPower >= 60 && st.morale <= 40) return resolve("mogok_biasa", state);
  if (f.joinedHQ) return resolve("hq_puppet", state);
  if (st.morale >= 45 && st.stability >= 45) return resolve("menengah", state);
  if (st.morale < 30 && st.stability < 30) return resolve("stuck", state);

  return resolve("netral_biasa", state);
}

// Fase 7: epilog hari-10 yang mereferensi faksi / Bazzaar / "Bapak Omong Kosong".
function epilogLine(state) {
  const f = state.factions || { hq: 50, serikat: 50, hero: 50, grem: 50 };
  const dom = Object.entries(f).sort((a, b) => b[1] - a[1])[0];
  const domName = { hq: "Dewan HQ", serikat: "Serikat Minion", hero: "Hero Party", grem: "Grem" }[dom[0]];
  const bits = [];
  bits.push(`Di akhir hari ke-10, faksi terkuat ternyata ${domName} (${dom[1]}%). Merekalah yang menentukan apakah ceritamu disebut "kemenangan" atau cuma "laporan triwulanan".`);
  if (state.flags.noAds) bits.push("Bazzaar sudah kamu beli paket 'hapus iklan'. Iklan memang tak pernah ada — tapi dompetmu merasa produktif.");
  if (state.flags.exploit) bits.push("Dan spanduk itu tetap terpampang di lorong utara: 'BOS = Bapak Omong Kosong'. Resmi, tertanda Serikat.");
  else if (state.flags.treatWell) bits.push("Serikat, untungnya, pakai spanduk lain: 'BOS = Bapak Omong Manis'. Murah hati, tapi tetap omong.");
  else bits.push("Serikat belum bikin spanduk. Itu lebih menakutkan dari spanduk itu sendiri.");
  return bits;
}

function resolve(id, state) {
  const ending = ENDINGS.find(e => e.id === id) || ENDINGS[ENDINGS.length - 1];
  const body = (ending.body || []).map(p => (typeof p === "function" ? p(state) : p));
  return {
    ...ending,
    body: body.concat(epilogLine(state))
  };
}

